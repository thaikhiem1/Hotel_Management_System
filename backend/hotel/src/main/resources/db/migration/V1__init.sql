CREATE TABLE IF NOT EXISTS LoaiPhong (
    IdLPH INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TenLPH VARCHAR(100) NOT NULL,
    SoGiuong INTEGER NOT NULL DEFAULT 1,
    SoNguoiToiDa INTEGER NOT NULL DEFAULT 1,
    GiaNgay NUMERIC(18,2) NOT NULL DEFAULT 0,
    GiaGio NUMERIC(18,2) NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS Phong (
    IdPH INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MaPH VARCHAR(20) NOT NULL UNIQUE,
    TrangThaiPhong VARCHAR(50) NOT NULL DEFAULT 'TRONG',
    IdLPH INTEGER NOT NULL,
    GhiChu VARCHAR(255),
    CONSTRAINT fk_phong_loaiphong FOREIGN KEY (IdLPH) REFERENCES LoaiPhong(IdLPH)
);
