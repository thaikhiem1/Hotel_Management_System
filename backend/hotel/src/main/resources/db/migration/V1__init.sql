CREATE TABLE IF NOT EXISTS employees (
    employee_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    position VARCHAR(50) NOT NULL,
    salary NUMERIC(18,2) NOT NULL DEFAULT 0,
    phone VARCHAR(15) NOT NULL UNIQUE,
    citizen_id VARCHAR(20) NOT NULL UNIQUE,
    date_of_birth DATE NOT NULL,
    gender VARCHAR(10) NOT NULL,
    address VARCHAR(255),
    email VARCHAR(100) NOT NULL UNIQUE,
    avatar VARCHAR(255),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT chk_employee_salary CHECK ( salary >= 0)
);

CREATE TABLE IF NOT EXISTS room_types (
    room_type_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_type_name VARCHAR(100) NOT NULL UNIQUE,
    number_of_beds INTEGER NOT NULL DEFAULT 1,
    maximum_occupancy INTEGER NOT NULL DEFAULT 2,
    daily_rate NUMERIC(18,2) NOT NULL DEFAULT 0,
    hourly_rate NUMERIC(18,2) DEFAULT 0,

    CONSTRAINT chk_room_type_beds
        CHECK (number_of_beds > 0),

    CONSTRAINT chk_room_type_occupancy
        CHECK (maximum_occupancy > 0),

    CONSTRAINT chk_room_type_daily_rate
        CHECK (daily_rate >= 0),

    CONSTRAINT chk_room_type_hourly_rate
        CHECK (hourly_rate >= 0)
);

CREATE TABLE IF NOT EXISTS rooms (
    room_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_code VARCHAR(20) NOT NULL UNIQUE,
    -- AVAILABLE: Phòng trống
    -- UNDER_MAINTENANCE: Đang sửa chữa
    room_status VARCHAR(30) NOT NULL DEFAULT 'AVAILABLE',
    room_type_id INTEGER NOT NULL,
    note VARCHAR(255),
    CONSTRAINT fk_room_room_type FOREIGN KEY (room_type_id) REFERENCES room_types(room_type_id),
    CONSTRAINT chk_room_status
        CHECK (room_status IN ('AVAILABLE', 'UNDER_MAINTENANCE'))
);

CREATE TABLE IF NOT EXISTS customers (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    phone VARCHAR(15) NOT NULL UNIQUE,
    citizen_id_passport VARCHAR(30) NOT NULL UNIQUE,
    nationality VARCHAR(50) NOT NULL,
    gender VARCHAR(10) NOT NULL
);
CREATE TABLE IF NOT EXISTS accounts (
    username VARCHAR(50) PRIMARY KEY,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(30) NOT NULL DEFAULT 'RECEPTIONIST',
    employee_id INTEGER NOT NULL UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT fk_account_employee
        FOREIGN KEY (employee_id)
        REFERENCES employees(employee_id),

    CONSTRAINT chk_account_role
        CHECK (role IN ('ADMIN','MANAGER' , 'RECEPTIONIST'))
);
CREATE TABLE IF NOT EXISTS service_categories (
    service_category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(100) NOT NULL
);
CREATE TABLE IF NOT EXISTS services (
    service_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_name VARCHAR(100) NOT NULL,
    unit_price NUMERIC(18,2) NOT NULL,
    stock_quantity INTEGER,
    unit VARCHAR(20) NOT NULL,
    service_category_id INTEGER NOT NULL,

    CONSTRAINT fk_service_category
        FOREIGN KEY (service_category_id)
        REFERENCES service_categories(service_category_id),

    CONSTRAINT chk_service_unit_price
        CHECK (unit_price >= 0),

    CONSTRAINT chk_service_stock
        CHECK (stock_quantity IS NULL OR stock_quantity >= 0)
);
