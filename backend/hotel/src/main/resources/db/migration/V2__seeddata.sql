CREATE TABLE IF NOT EXISTS NhanVien (
    IdNV INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TenNV VARCHAR(100) NOT NULL,
    ChucVu VARCHAR(50),
    Luong NUMERIC(18,2),
    SDT VARCHAR(15),
    CCCD VARCHAR(20) UNIQUE,
    NgaySinh DATE,
    GioiTinh VARCHAR(10),
    DiaChi VARCHAR(255),
    Email VARCHAR(100),
    Avatar VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS TaiKhoan (
    TenTK VARCHAR(50) PRIMARY KEY,
    Password_hash VARCHAR(255) NOT NULL,
    Role INTEGER NOT NULL,
    IdNV INTEGER NOT NULL UNIQUE,
    CONSTRAINT fk_taikhoan_nhanvien FOREIGN KEY (IdNV) REFERENCES NhanVien(IdNV)
);

