CREATE TABLE IF NOT EXISTS NhanVien (
    IdNV INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TenNV VARCHAR(100) NOT NULL,
    ChucVu varchar(50) NOT NULL,
    Luong NUMERIC(18,2) NOT NULL DEFAULT 0,
    SDT   CHAR(10) NOT NULL UNIQUE,
    CCCD  CHAR(12) NOT NULL UNIQUE,
    NgaySinh DATE NOT NULL,
    GioiTinh VARCHAR(10) NOT NULL,
    DiaChi VARCHAR(255),
    Email VARCHAR(100) NOT NULL UNIQUE,
    Avatar TEXT,
    CONSTRAINT CK_Luong_NhanVien CHECK(Luong >= 0),
    CONSTRAINT CK_GioiTinh_NhanVien CHECK(GioiTinh IN ('Nam', 'Nữ', 'Khác'))
)

