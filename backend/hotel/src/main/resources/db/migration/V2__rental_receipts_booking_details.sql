-- =========================================================
-- V2: Phiếu thuê (rental_receipts) và chi tiết đặt phòng (booking_details)
-- Phục vụ UC-REN-001 (tạo phiếu thuê), UC-REN-009 (tra cứu phòng khả dụng),
-- UC-REN-010 (tính chi phí) và là nền cho UC-REN-004 (nhận phòng), UC-REN-007 (trả phòng).
-- Thiết kế theo docs/Database.md; các quy tắc nghiệp vụ được ép ngay ở tầng DB
-- để dữ liệu luôn đúng kể cả khi hai giao dịch chạy đồng thời (UC-REN-001 A9, UC-REN-009 E5).
-- =========================================================

-- Cần cho EXCLUDE USING gist trên (room_id, khoảng thời gian)
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- =========================================================
-- 1. RENTAL RECEIPTS - Phiếu thuê
-- =========================================================
CREATE TABLE IF NOT EXISTS rental_receipts (
    rental_receipt_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Mã phiếu duy nhất, do hệ thống sinh từ khóa chính (trigger bên dưới), ví dụ PT007
    receipt_code           VARCHAR(20) NOT NULL UNIQUE,
    rental_date            TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    customer_id            INTEGER NOT NULL,   -- khách hàng đại diện (BR-REN-001-01)
    employee_id            INTEGER NOT NULL,   -- nhân viên lập phiếu, lấy từ tài khoản đăng nhập (BR-REN-001-03)

    -- DA_XAC_NHAN: đã xác nhận | DANG_LUU_TRU: đang lưu trú
    -- DA_TRA_PHONG: đã trả phòng | DA_HUY: đã hủy
    receipt_status         VARCHAR(20) NOT NULL DEFAULT 'DA_XAC_NHAN',

    -- Tổng chi phí dự kiến = SUM(booking_details.estimated_amount) (BR-REN-001-10),
    -- do trigger trg_booking_details_refresh_total tự cập nhật, không nhận từ giao diện
    estimated_total_amount NUMERIC(18,2) NOT NULL DEFAULT 0,

    -- Lịch sử hủy toàn bộ phiếu (UC-REN-003)
    cancelled_at           TIMESTAMP,
    cancelled_by           INTEGER,
    cancel_reason          VARCHAR(255),

    -- Khóa lạc quan (optimistic locking) cho JPA @Version
    version                INTEGER NOT NULL DEFAULT 0,

    CONSTRAINT fk_rental_receipt_customer FOREIGN KEY (customer_id)
        REFERENCES customers(customer_id),
    CONSTRAINT fk_rental_receipt_employee FOREIGN KEY (employee_id)
        REFERENCES employees(employee_id),
    CONSTRAINT fk_rental_receipt_cancelled_by FOREIGN KEY (cancelled_by)
        REFERENCES employees(employee_id),

    CONSTRAINT chk_receipt_status
        CHECK (receipt_status IN ('DA_XAC_NHAN', 'DANG_LUU_TRU', 'DA_TRA_PHONG', 'DA_HUY')),
    CONSTRAINT chk_receipt_estimated_total CHECK (estimated_total_amount >= 0),
    CONSTRAINT chk_receipt_cancel_info CHECK (
        (receipt_status = 'DA_HUY'  AND cancelled_at IS NOT NULL)
     OR (receipt_status <> 'DA_HUY' AND cancelled_at IS NULL)
    )
);

CREATE INDEX IF NOT EXISTS idx_rental_receipts_customer ON rental_receipts (customer_id);
CREATE INDEX IF NOT EXISTS idx_rental_receipts_employee ON rental_receipts (employee_id);
CREATE INDEX IF NOT EXISTS idx_rental_receipts_date     ON rental_receipts (rental_date);

-- =========================================================
-- 2. BOOKING DETAILS - Chi tiết đặt phòng
-- =========================================================
CREATE TABLE IF NOT EXISTS booking_details (
    booking_detail_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_receipt_id       INTEGER NOT NULL,
    room_id                 INTEGER NOT NULL,

    number_of_guests        INTEGER NOT NULL,   -- dự kiến
    actual_number_of_guests INTEGER,            -- ghi nhận khi check-in (UC-REN-004)

    -- Thời gian dự kiến
    check_in_at             TIMESTAMP NOT NULL,
    check_out_at            TIMESTAMP NOT NULL,
    -- Thời gian thực tế
    actual_check_in_at      TIMESTAMP,
    actual_check_out_at     TIMESTAMP,

    -- RESERVED: đã đặt | CHECKED_IN: đang thuê
    -- CHECKED_OUT: đã trả phòng | CANCELLED: đã hủy
    booking_status          VARCHAR(20) NOT NULL DEFAULT 'RESERVED',

    -- Phương thức tính giá: NGAY (theo đêm) | GIO (theo giờ)
    pricing_method          VARCHAR(10) NOT NULL,
    -- Đơn giá đã chốt tại thời điểm tạo phiếu, lưu riêng từng chi tiết (BR-REN-001-09)
    unit_price              NUMERIC(18,2) NOT NULL,
    -- Số đêm/giờ tính tiền dự kiến và thành tiền dự kiến (UC-REN-010)
    estimated_units         INTEGER NOT NULL,
    estimated_amount        NUMERIC(18,2) NOT NULL,

    -- Lịch sử hủy chi tiết (UC-REN-002)
    cancelled_at            TIMESTAMP,
    cancelled_by            INTEGER,
    cancel_reason           VARCHAR(255),

    version                 INTEGER NOT NULL DEFAULT 0,

    CONSTRAINT fk_booking_detail_rental_receipt FOREIGN KEY (rental_receipt_id)
        REFERENCES rental_receipts(rental_receipt_id),
    CONSTRAINT fk_booking_detail_room FOREIGN KEY (room_id)
        REFERENCES rooms(room_id),
    CONSTRAINT fk_booking_detail_cancelled_by FOREIGN KEY (cancelled_by)
        REFERENCES employees(employee_id),

    CONSTRAINT chk_booking_number_of_guests CHECK (number_of_guests > 0),
    CONSTRAINT chk_booking_actual_guests
        CHECK (actual_number_of_guests IS NULL OR actual_number_of_guests > 0),
    -- Thời gian trả phải sau thời gian nhận (BR-REN-001-06)
    CONSTRAINT chk_booking_date CHECK (check_out_at > check_in_at),

    -- Không nhận phòng trước giờ dự kiến (UC-REN-004)
    CONSTRAINT chk_actual_check_in
        CHECK (actual_check_in_at IS NULL OR actual_check_in_at >= check_in_at),
    CONSTRAINT chk_actual_check_out
        CHECK (actual_check_out_at IS NULL
               OR (actual_check_in_at IS NOT NULL AND actual_check_out_at >= actual_check_in_at)),

    CONSTRAINT chk_booking_pricing_method CHECK (pricing_method IN ('NGAY', 'GIO')),
    CONSTRAINT chk_booking_unit_price CHECK (unit_price >= 0),
    CONSTRAINT chk_booking_estimated_units CHECK (estimated_units > 0),
    -- Thành tiền = số đêm/giờ x đơn giá đã chốt (UC-REN-010, BR-REN-010-02)
    CONSTRAINT chk_booking_estimated_amount
        CHECK (estimated_amount >= 0 AND estimated_amount = ROUND(unit_price * estimated_units, 2)),
    -- Cách tính số đơn vị (BR-REN-010-09, BR-REN-010-10):
    --   GIO : làm tròn lên theo tổng thời lượng, tối thiểu 1 giờ
    --   NGAY: số đêm giữa ngày nhận và ngày trả, thuê qua ngày tối thiểu 1 đêm
    -- Khi chính sách giá đổi, thay constraint này bằng một migration mới.
    CONSTRAINT chk_booking_estimated_units_rule CHECK (
        estimated_units = CASE pricing_method
            WHEN 'GIO' THEN GREATEST(1, CEIL(EXTRACT(EPOCH FROM (check_out_at - check_in_at)) / 3600)::INTEGER)
            ELSE GREATEST(1, (check_out_at::DATE - check_in_at::DATE))
        END
    ),

    CONSTRAINT chk_booking_status
        CHECK (booking_status IN ('RESERVED', 'CHECKED_IN', 'CHECKED_OUT', 'CANCELLED')),

    -- Dữ liệu thời gian/hủy phải khớp với trạng thái (BR-REN-001-11)
    CONSTRAINT chk_booking_status_consistency CHECK (
        (booking_status = 'RESERVED'
            AND actual_check_in_at IS NULL AND actual_check_out_at IS NULL AND cancelled_at IS NULL)
     OR (booking_status = 'CHECKED_IN'
            AND actual_check_in_at IS NOT NULL AND actual_number_of_guests IS NOT NULL
            AND actual_check_out_at IS NULL AND cancelled_at IS NULL)
     OR (booking_status = 'CHECKED_OUT'
            AND actual_check_in_at IS NOT NULL AND actual_check_out_at IS NOT NULL
            AND cancelled_at IS NULL)
     OR (booking_status = 'CANCELLED'
            AND actual_check_in_at IS NULL AND cancelled_at IS NOT NULL)
    ),

    -- Không chồng lấn lịch của cùng một phòng với các lượt còn hiệu lực (BR-REN-001-07).
    -- Range '[)' nên hai khoảng tiếp giáp không bị xem là chồng lấn (BR-REN-009-04).
    -- CANCELLED và CHECKED_OUT không giữ chỗ (BR-REN-009-09).
    -- Ràng buộc này chặn cả trường hợp hai giao dịch cùng đặt một phòng (UC-REN-001 A9).
    CONSTRAINT excl_booking_room_overlap EXCLUDE USING gist (
        room_id WITH =,
        tsrange(check_in_at, check_out_at, '[)') WITH &&
    ) WHERE (booking_status IN ('RESERVED', 'CHECKED_IN'))
);

-- Mỗi phòng chỉ xuất hiện một lần trong cùng phiếu thuê (BR-REN-001-04)
CREATE UNIQUE INDEX IF NOT EXISTS uq_booking_receipt_room_active
    ON booking_details (rental_receipt_id, room_id)
    WHERE booking_status <> 'CANCELLED';

-- Một phòng chỉ có tối đa một lượt đang lưu trú (UC-REN-004 E4, E5)
CREATE UNIQUE INDEX IF NOT EXISTS uq_booking_room_checked_in
    ON booking_details (room_id)
    WHERE booking_status = 'CHECKED_IN';

CREATE INDEX IF NOT EXISTS idx_booking_details_receipt ON booking_details (rental_receipt_id);
CREATE INDEX IF NOT EXISTS idx_booking_details_room_status ON booking_details (room_id, booking_status);

-- =========================================================
-- 3. TRIGGERS
-- =========================================================

-- 3.1 Sinh mã phiếu thuê (VC-13): PT + id, tối thiểu 3 chữ số (PT001, PT1234).
--     Luôn ghi đè giá trị client gửi lên để mã do hệ thống sinh.
CREATE OR REPLACE FUNCTION fn_set_receipt_code() RETURNS TRIGGER AS $$
BEGIN
    NEW.receipt_code := 'PT' || LPAD(
        NEW.rental_receipt_id::TEXT,
        GREATEST(3, LENGTH(NEW.rental_receipt_id::TEXT)),
        '0');
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_rental_receipts_set_code
    BEFORE INSERT ON rental_receipts
    FOR EACH ROW EXECUTE FUNCTION fn_set_receipt_code();

-- 3.2 Kiểm tra theo dữ liệu phòng (không biểu diễn được bằng CHECK vì liên quan bảng khác):
--     - Số khách (dự kiến/thực tế) không vượt sức chứa tối đa của loại phòng (BR-REN-001-05)
--     - Không tạo đặt phòng cho phòng đang bảo trì hoặc đang dọn dẹp (Validity Check 5)
CREATE OR REPLACE FUNCTION fn_validate_booking_detail() RETURNS TRIGGER AS $$
DECLARE
    v_room_code VARCHAR;
    v_status    VARCHAR;
    v_max       INTEGER;
BEGIN
    SELECT r.room_code, r.room_status, rt.maximum_occupancy
      INTO v_room_code, v_status, v_max
      FROM rooms r
      JOIN room_types rt ON rt.room_type_id = r.room_type_id
     WHERE r.room_id = NEW.room_id;

    IF NOT FOUND THEN
        RETURN NEW; -- để khóa ngoại fk_booking_detail_room báo lỗi
    END IF;

    IF TG_OP = 'INSERT'
       OR NEW.room_id IS DISTINCT FROM OLD.room_id
       OR NEW.number_of_guests IS DISTINCT FROM OLD.number_of_guests
       OR NEW.actual_number_of_guests IS DISTINCT FROM OLD.actual_number_of_guests THEN
        IF NEW.number_of_guests > v_max
           OR COALESCE(NEW.actual_number_of_guests, 0) > v_max THEN
            RAISE EXCEPTION 'Phòng % chỉ cho phép tối đa % khách', v_room_code, v_max
                USING ERRCODE = '23514';
        END IF;
    END IF;

    IF TG_OP = 'INSERT' AND NEW.booking_status = 'RESERVED'
       AND v_status IN ('UNDER_MAINTENANCE', 'CLEANING') THEN
        RAISE EXCEPTION 'Phòng % đang ở trạng thái % nên không thể đặt', v_room_code, v_status
            USING ERRCODE = '23514';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_booking_details_validate
    BEFORE INSERT OR UPDATE ON booking_details
    FOR EACH ROW EXECUTE FUNCTION fn_validate_booking_detail();

-- 3.3 Tổng chi phí dự kiến của phiếu = tổng thành tiền các chi tiết chưa bị hủy (BR-REN-001-10)
CREATE OR REPLACE FUNCTION fn_recalc_receipt_total(p_receipt_id INTEGER) RETURNS VOID AS $$
BEGIN
    UPDATE rental_receipts rr
       SET estimated_total_amount = COALESCE((
               SELECT SUM(bd.estimated_amount)
                 FROM booking_details bd
                WHERE bd.rental_receipt_id = p_receipt_id
                  AND bd.booking_status <> 'CANCELLED'), 0)
     WHERE rr.rental_receipt_id = p_receipt_id;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION fn_booking_details_refresh_total() RETURNS TRIGGER AS $$
BEGIN
    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        PERFORM fn_recalc_receipt_total(NEW.rental_receipt_id);
    END IF;
    IF TG_OP = 'DELETE'
       OR (TG_OP = 'UPDATE' AND OLD.rental_receipt_id IS DISTINCT FROM NEW.rental_receipt_id) THEN
        PERFORM fn_recalc_receipt_total(OLD.rental_receipt_id);
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_booking_details_refresh_total
    AFTER INSERT OR DELETE OR UPDATE OF estimated_amount, booking_status, rental_receipt_id
    ON booking_details
    FOR EACH ROW EXECUTE FUNCTION fn_booking_details_refresh_total();

-- 3.4 Phiếu thuê phải có ít nhất một chi tiết đặt phòng (BR-REN-001-01).
--     Kiểm tra hoãn đến lúc COMMIT để vẫn insert phiếu trước, chi tiết sau trong cùng transaction.
CREATE OR REPLACE FUNCTION fn_check_receipt_has_detail() RETURNS TRIGGER AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM booking_details WHERE rental_receipt_id = NEW.rental_receipt_id) THEN
        RAISE EXCEPTION 'Phiếu thuê % phải có ít nhất một chi tiết đặt phòng', NEW.receipt_code
            USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE CONSTRAINT TRIGGER trg_rental_receipts_require_detail
    AFTER INSERT ON rental_receipts
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_check_receipt_has_detail();
