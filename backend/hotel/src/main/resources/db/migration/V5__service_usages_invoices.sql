-- =========================================================
-- V5: Dịch vụ khách sử dụng và hóa đơn trả phòng
--     Phục vụ UC-REN-007 (trả phòng) và UC-SVC-005 (ghi nhận dịch vụ khách sử dụng)
-- =========================================================

-- =========================================================
-- 1. SERVICE USAGES - Dịch vụ khách đã sử dụng trong một lượt lưu trú
-- =========================================================
CREATE TABLE IF NOT EXISTS service_usages (
    service_usage_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_detail_id INTEGER NOT NULL,        -- lượt lưu trú (chi tiết đặt phòng)
    service_id        INTEGER NOT NULL,
    quantity          INTEGER NOT NULL,
    -- Đơn giá áp dụng tại thời điểm ghi nhận, không đổi khi đơn giá dịch vụ hiện hành đổi (UC-SVC-005 quy tắc 9)
    unit_price        NUMERIC(18,2) NOT NULL,
    amount            NUMERIC(18,2) NOT NULL,  -- thành tiền = số lượng x đơn giá áp dụng
    used_at           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    recorded_by       INTEGER NOT NULL,        -- nhân viên ghi nhận

    CONSTRAINT fk_service_usage_booking_detail FOREIGN KEY (booking_detail_id)
        REFERENCES booking_details(booking_detail_id),
    CONSTRAINT fk_service_usage_service FOREIGN KEY (service_id)
        REFERENCES services(service_id),
    CONSTRAINT fk_service_usage_employee FOREIGN KEY (recorded_by)
        REFERENCES employees(employee_id),

    CONSTRAINT chk_service_usage_quantity CHECK (quantity > 0),
    CONSTRAINT chk_service_usage_unit_price CHECK (unit_price >= 0),
    CONSTRAINT chk_service_usage_amount CHECK (amount = ROUND(unit_price * quantity, 2))
);

CREATE INDEX IF NOT EXISTS idx_service_usages_booking_detail ON service_usages (booking_detail_id);
CREATE INDEX IF NOT EXISTS idx_service_usages_service ON service_usages (service_id);

-- Chỉ ghi dịch vụ cho lượt lưu trú đang diễn ra (UC-SVC-005 quy tắc 2, 3)
CREATE OR REPLACE FUNCTION fn_validate_service_usage() RETURNS TRIGGER AS $$
DECLARE
    v_status VARCHAR;
BEGIN
    SELECT booking_status INTO v_status
      FROM booking_details WHERE booking_detail_id = NEW.booking_detail_id;

    IF FOUND AND v_status <> 'CHECKED_IN' THEN
        RAISE EXCEPTION 'Chỉ ghi nhận dịch vụ cho lượt lưu trú đang diễn ra'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_service_usages_validate
    BEFORE INSERT ON service_usages
    FOR EACH ROW EXECUTE FUNCTION fn_validate_service_usage();

-- =========================================================
-- 2. INVOICES - Hóa đơn trả phòng (mỗi lượt lưu trú tối đa một hóa đơn)
-- =========================================================
CREATE TABLE IF NOT EXISTS invoices (
    invoice_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Mã hóa đơn duy nhất do hệ thống sinh từ khóa chính (trigger bên dưới), ví dụ HD007
    invoice_code      VARCHAR(20) NOT NULL UNIQUE,
    -- Mỗi chi tiết lưu trú chỉ có một hóa đơn trả phòng (UC-REN-007 quy tắc 3, E3)
    booking_detail_id INTEGER NOT NULL UNIQUE,
    rental_receipt_id INTEGER NOT NULL,
    employee_id       INTEGER NOT NULL,        -- nhân viên thực hiện trả phòng

    -- Giá đã chốt của lượt lưu trú và cách tính tiền phòng theo thời gian thực tế
    pricing_method    VARCHAR(10) NOT NULL,
    unit_price        NUMERIC(18,2) NOT NULL,
    billed_units      INTEGER NOT NULL,
    room_amount       NUMERIC(18,2) NOT NULL,
    service_amount    NUMERIC(18,2) NOT NULL DEFAULT 0,
    -- Tổng tiền cuối cùng = tiền phòng + tiền dịch vụ, được lưu để xem hóa đơn không làm đổi số tiền
    total_amount      NUMERIC(18,2) NOT NULL,

    -- Trả phòng không đồng nghĩa với thanh toán: hóa đơn mới luôn UNPAID
    invoice_status    VARCHAR(10) NOT NULL DEFAULT 'UNPAID',
    issued_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paid_at           TIMESTAMP,

    version           INTEGER NOT NULL DEFAULT 0,

    CONSTRAINT fk_invoice_booking_detail FOREIGN KEY (booking_detail_id)
        REFERENCES booking_details(booking_detail_id),
    CONSTRAINT fk_invoice_rental_receipt FOREIGN KEY (rental_receipt_id)
        REFERENCES rental_receipts(rental_receipt_id),
    CONSTRAINT fk_invoice_employee FOREIGN KEY (employee_id)
        REFERENCES employees(employee_id),

    CONSTRAINT chk_invoice_pricing_method CHECK (pricing_method IN ('NGAY', 'GIO')),
    CONSTRAINT chk_invoice_unit_price CHECK (unit_price >= 0),
    CONSTRAINT chk_invoice_billed_units CHECK (billed_units > 0),
    CONSTRAINT chk_invoice_room_amount CHECK (room_amount = ROUND(unit_price * billed_units, 2)),
    CONSTRAINT chk_invoice_service_amount CHECK (service_amount >= 0),
    CONSTRAINT chk_invoice_total_amount CHECK (total_amount = room_amount + service_amount),
    CONSTRAINT chk_invoice_status CHECK (invoice_status IN ('UNPAID', 'PAID')),
    CONSTRAINT chk_invoice_paid_info CHECK (
        (invoice_status = 'PAID'   AND paid_at IS NOT NULL)
     OR (invoice_status = 'UNPAID' AND paid_at IS NULL)
    )
);

CREATE INDEX IF NOT EXISTS idx_invoices_receipt ON invoices (rental_receipt_id);
CREATE INDEX IF NOT EXISTS idx_invoices_status ON invoices (invoice_status);

-- Sinh mã hóa đơn: HD + id, tối thiểu 3 chữ số (HD001, HD1234); luôn ghi đè giá trị client gửi lên
CREATE OR REPLACE FUNCTION fn_set_invoice_code() RETURNS TRIGGER AS $$
BEGIN
    NEW.invoice_code := 'HD' || LPAD(
        NEW.invoice_id::TEXT,
        GREATEST(3, LENGTH(NEW.invoice_id::TEXT)),
        '0');
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_invoices_set_code
    BEFORE INSERT ON invoices
    FOR EACH ROW EXECUTE FUNCTION fn_set_invoice_code();

-- Hóa đơn phải khớp lượt lưu trú đã trả phòng: cùng phiếu, cùng giá đã chốt, số đơn vị theo thời gian thực tế
-- (cùng quy tắc với tính giá phiếu thuê: GIO làm tròn lên theo giờ, NGAY theo số đêm, tối thiểu 1)
-- và tiền dịch vụ bằng tổng thành tiền các dịch vụ đã ghi nhận.
CREATE OR REPLACE FUNCTION fn_validate_invoice() RETURNS TRIGGER AS $$
DECLARE
    d              booking_details%ROWTYPE;
    v_units        INTEGER;
    v_service_sum  NUMERIC(18,2);
BEGIN
    SELECT * INTO d FROM booking_details WHERE booking_detail_id = NEW.booking_detail_id;
    IF NOT FOUND THEN
        RETURN NEW; -- để khóa ngoại báo lỗi
    END IF;

    IF d.booking_status <> 'CHECKED_OUT' THEN
        RAISE EXCEPTION 'Chỉ lập hóa đơn cho lượt lưu trú đã trả phòng' USING ERRCODE = '23514';
    END IF;
    IF d.rental_receipt_id <> NEW.rental_receipt_id
       OR d.pricing_method <> NEW.pricing_method
       OR d.unit_price <> NEW.unit_price THEN
        RAISE EXCEPTION 'Hóa đơn không khớp phiếu thuê hoặc đơn giá đã chốt của lượt lưu trú'
            USING ERRCODE = '23514';
    END IF;

    v_units := CASE d.pricing_method
        WHEN 'GIO' THEN GREATEST(1, CEIL(EXTRACT(EPOCH FROM (d.actual_check_out_at - d.actual_check_in_at)) / 3600)::INTEGER)
        ELSE GREATEST(1, (d.actual_check_out_at::DATE - d.actual_check_in_at::DATE))
    END;
    IF NEW.billed_units <> v_units THEN
        RAISE EXCEPTION 'Số đơn vị tính tiền phòng không khớp thời gian lưu trú thực tế' USING ERRCODE = '23514';
    END IF;

    SELECT COALESCE(SUM(amount), 0) INTO v_service_sum
      FROM service_usages WHERE booking_detail_id = NEW.booking_detail_id;
    IF NEW.service_amount <> v_service_sum THEN
        RAISE EXCEPTION 'Tiền dịch vụ không khớp các dịch vụ đã ghi nhận' USING ERRCODE = '23514';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_invoices_validate
    BEFORE INSERT ON invoices
    FOR EACH ROW EXECUTE FUNCTION fn_validate_invoice();

-- Số tiền và dữ liệu đã chốt không đổi sau khi lập; chỉ trạng thái thanh toán được cập nhật
CREATE OR REPLACE FUNCTION fn_invoice_immutable() RETURNS TRIGGER AS $$
BEGIN
    IF NEW.booking_detail_id <> OLD.booking_detail_id
       OR NEW.rental_receipt_id <> OLD.rental_receipt_id
       OR NEW.pricing_method <> OLD.pricing_method
       OR NEW.unit_price <> OLD.unit_price
       OR NEW.billed_units <> OLD.billed_units
       OR NEW.room_amount <> OLD.room_amount
       OR NEW.service_amount <> OLD.service_amount
       OR NEW.total_amount <> OLD.total_amount THEN
        RAISE EXCEPTION 'Không được thay đổi số tiền của hóa đơn đã lập' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_invoices_immutable
    BEFORE UPDATE ON invoices
    FOR EACH ROW EXECUTE FUNCTION fn_invoice_immutable();
