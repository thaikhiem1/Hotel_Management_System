-- Xung đột lợi ích: GVPB không được là GVHD của cùng đề tài
CREATE FUNCTION fn_vaitro_gvpb_khac_gvhd() RETURNS trigger AS $$
BEGIN
    IF NEW.NgayKetThuc IS NULL AND EXISTS (
        SELECT 1 FROM VAITROGIANGVIEN v
        WHERE v.MaDeTai = NEW.MaDeTai
          AND v.MaGiangVien = NEW.MaGiangVien
          AND v.NgayKetThuc IS NULL
          AND v.LoaiVaiTro <> NEW.LoaiVaiTro
          AND v.MaVaiTro IS DISTINCT FROM NEW.MaVaiTro)
    THEN
        RAISE EXCEPTION 'GVPB không được là GVHD của cùng một đề tài'
              USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_vaitro_gvpb_khac_gvhd
    BEFORE INSERT OR UPDATE ON VAITROGIANGVIEN
    FOR EACH ROW EXECUTE FUNCTION fn_vaitro_gvpb_khac_gvhd();

