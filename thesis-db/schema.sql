-- =====================================================================
-- HỆ THỐNG QUẢN LÝ ĐỀ TÀI NCKH / KLTN  -  SCHEMA TỔNG THỂ (PostgreSQL 16)
-- 35 bảng, 7 cụm  =  31 bảng trong tài liệu  +  4 bảng bổ sung
--   Bảng bổ sung: LICHSUXETDUYET, TONGHOPDIEM, LICHRANHGIANGVIEN, MAUTHONGBAO
--
-- Quy ước
--   * Tên bảng/cột giữ đúng tài liệu. Postgres tự đổi tên không đặt trong
--     dấu nháy về CHỮ THƯỜNG (MaNguoiDung -> manguoidung). EF Core phải map
--     tên chữ thường (xem ghi chú cuối file).
--   * NVARCHAR(n) -> VARCHAR(n); NVARCHAR(MAX) -> TEXT; JSON -> JSONB
--     DATETIME2 -> TIMESTAMPTZ (lưu UTC); BIT -> BOOLEAN
--   * Khóa chính tự tăng: GENERATED BY DEFAULT AS IDENTITY (cho phép seed id)
--   * Không dùng ON DELETE CASCADE: dữ liệu nghiệp vụ chỉ xóa mềm/đổi trạng thái
--   * Chống cập nhật đồng thời: dùng cột hệ thống xmin làm concurrency token
--   * CHECK chỉ đặt ở những cột mà tài liệu liệt kê rõ danh sách giá trị.
--     Các cột còn lại ghi "Gợi ý giá trị" trong chú thích.
--   * Thứ tự tạo bảng theo phụ thuộc khóa ngoại (không có vòng tham chiếu,
--     riêng YEUCAU.MaLich thêm bằng ALTER ở cuối cụm 5)
-- =====================================================================

